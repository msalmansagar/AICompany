/**
 * Seed: a manually-built summary tab on three-changes-demo.
 *
 * Adds a 4th tab marked as the summary step (qdb_is_summary_tab) and switches the form to
 * summaryMode = Manual, so the maker owns the review page instead of the engine building
 * one. On it sits a READ-ONLY file field bound with qdb_source_field_schema_name to the
 * upload field on tab 2 — that renders as a document list with View and Download only.
 *
 * Run:  node --env-file=scripts/.env scripts/seed-manual-summary-tab.mjs
 * Safe: guards on the field schema name — re-run is a no-op.
 */

const TENANT_ID     = 'd79e793c-f6de-4204-8508-7980a63df957';
const CLIENT_ID     = '08e80e93-0bab-45ef-8372-2e554fa9af9b';
const CLIENT_SECRET = process.env.DV_CLIENT_SECRET;
const DV            = 'https://org5869857f.crm4.dynamics.com';
const BASE          = `${DV}/api/data/v9.2`;
const FORM_CODE     = 'three-changes-demo';
const FIELD_SCHEMA  = 'demo3_summary_docs';
const SOURCE_SCHEMA = 'demo3_supporting_docs';

const tokenJson = await fetch(
  `https://login.microsoftonline.com/${TENANT_ID}/oauth2/v2.0/token`,
  { method: 'POST', headers: { 'Content-Type': 'application/x-www-form-urlencoded' },
    body: new URLSearchParams({
      grant_type: 'client_credentials', client_id: CLIENT_ID,
      client_secret: CLIENT_SECRET, scope: `${DV}/.default`,
    }) },
).then((r) => r.json());
if (!tokenJson.access_token) throw new Error(tokenJson.error_description ?? 'Token request failed');

const H = {
  Authorization: `Bearer ${tokenJson.access_token}`,
  'OData-MaxVersion': '4.0',
  'OData-Version': '4.0',
  Accept: 'application/json',
  'Content-Type': 'application/json',
  Prefer: 'return=representation',
};

const get = async (path) => {
  const r = await fetch(`${BASE}/${path}`, { headers: H });
  const j = await r.json();
  if (!r.ok) throw new Error(`GET ${path}: ${j.error?.message ?? r.status}`);
  return j;
};

const post = async (entity, body) => {
  const r = await fetch(`${BASE}/${entity}`, { method: 'POST', headers: H, body: JSON.stringify(body) });
  const text = await r.text();
  if (!r.ok) throw new Error(`POST ${entity}: ${text}`);
  return text ? JSON.parse(text) : {};
};

const patch = async (path, body) => {
  const r = await fetch(`${BASE}/${path}`, { method: 'PATCH', headers: H, body: JSON.stringify(body) });
  if (!r.ok) throw new Error(`PATCH ${path}: ${await r.text()}`);
  return r.status;
};

const FT  = { file: 100000015, infoCard: 100000020 };
const CS  = { two: 100000002 };
const COL = { one: 100000001 };
// qdb_summary_mode: 100000001 None · 100000002 SystemGenerated · 100000003 Manual
const SUMMARY_MODE_MANUAL = 100000003;
const ICS = { info: 100000000 };

console.log('\n== Manual summary tab — seed ==\n');

const existing = await get(
  `qdb_form_fields?$filter=qdb_schema_name eq '${FIELD_SCHEMA}'&$select=qdb_form_fieldid&$top=1`,
);
if (existing.value?.length) {
  console.log(`${FIELD_SCHEMA} already exists — nothing to do`);
  process.exit(0);
}

const form = await get(
  `qdb_form_definitions?$filter=qdb_form_code eq '${FORM_CODE}'&$select=qdb_form_definitionid,qdb_summary_mode&$top=1`,
);
const formId = form.value?.[0]?.qdb_form_definitionid;
if (!formId) throw new Error(`form ${FORM_CODE} not found`);

const tabs = await get(
  `qdb_form_tabs?$filter=_qdb_form_definition_id_value eq ${formId}&$select=qdb_form_tabid,qdb_display_order&$orderby=qdb_display_order desc`,
);
const lastOrder = tabs.value[0]?.qdb_display_order ?? 0;

// The summary tab has to come last — it is the review step before submit.
const tab = await post('qdb_form_tabs', {
  'qdb_form_definition_id@odata.bind': `/qdb_form_definitions(${formId})`,
  qdb_label: '4 · Review',
  qdb_description: 'A summary page built by hand, not generated by the engine.',
  qdb_display_order: lastOrder + 1,
  qdb_is_visible: true,
  qdb_is_summary_tab: true,
  qdb_requires_previous_tab_complete: false,
});
console.log(`tab created — ${tab.qdb_form_tabid}`);

const section = await post('qdb_form_sections', {
  'qdb_form_tab_id@odata.bind': `/qdb_form_tabs(${tab.qdb_form_tabid})`,
  qdb_label: 'Your documents',
  qdb_description: 'Read-only. The same files uploaded on tab 2, with View and Download only — nothing can be added, replaced or removed here.',
  qdb_display_order: 1,
  qdb_columns: COL.one,
  qdb_is_collapsible: false,
  qdb_is_collapsed_by_default: false,
  qdb_is_visible: true,
});

await post('qdb_form_fields', {
  'qdb_form_section_id@odata.bind': `/qdb_form_sections(${section.qdb_form_sectionid})`,
  qdb_schema_name: 'demo3_review_note',
  qdb_field_type: FT.infoCard,
  qdb_label: 'Before you submit',
  qdb_info_card_style: ICS.info,
  qdb_info_card_title: 'Check your attachments',
  qdb_info_card_body: 'Open each document to confirm you uploaded the right file. To change one, go back to the Documents tab.',
  qdb_display_order: 1,
  qdb_column_span: CS.two,
  qdb_is_required: false,
  qdb_is_readonly: false,
  qdb_is_hidden: false,
});

const field = await post('qdb_form_fields', {
  'qdb_form_section_id@odata.bind': `/qdb_form_sections(${section.qdb_form_sectionid})`,
  qdb_schema_name: FIELD_SCHEMA,
  qdb_field_type: FT.file,
  qdb_label: 'Supporting documents',
  qdb_tooltip: 'Read-only view of the documents uploaded on the Documents tab.',
  qdb_display_order: 2,
  qdb_column_span: CS.two,
  qdb_is_required: false,
  // Read-only turns the file field into a document display.
  qdb_is_readonly: true,
  qdb_is_hidden: false,
  // Bound to the upload field on tab 2 rather than carrying its own value.
  qdb_source_field_schema_name: SOURCE_SCHEMA,
});
console.log(`document display created — ${field.qdb_form_fieldid} (source: ${SOURCE_SCHEMA})`);

console.log(`summary mode → Manual : ${await patch(`qdb_form_definitions(${formId})`, { qdb_summary_mode: SUMMARY_MODE_MANUAL })}`);

console.log('\nseeded. Republish the form, then open tab 4.\n');
