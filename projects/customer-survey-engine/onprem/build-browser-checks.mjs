/**
 * OFFLINE. Writes the console scripts QDB IT pastes into the browser (F12) on each on-prem org, as a
 * System Administrator, into onprem-deploy/<date>/scripts/:
 *   survey-preflight-HL.console.js, survey-preflight-BFD.console.js   before any import
 *   survey-rollback-backup.console.js                                 before any import
 *   survey-post-import.console.js                                     after the imports and Publish All
 * Each one embeds onprem/checks/survey-checks.js, the kit facts and (preflight) the org's
 * configuration, runs read-only GETs, prints a table and downloads a JSON report to send back.
 *
 *   node onprem/build-browser-checks.mjs --date=2026-11-11
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { parseArgs } from 'node:util';
import { readKitFacts } from './lib/kit-facts.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const CHECKS = readFileSync(resolve(HERE, 'checks/survey-checks.js'), 'utf8').replace(/\nif \(typeof module[^\n]*\n?$/, '\n');
const ORGS = ['HL', 'BFD'];

// Runs in the browser: resolves the org's Web API from the page, injects get(), downloads the report.
const BROWSER_RUNNER = String.raw`
(async () => {
  const clientUrl = (() => {
    try { return window.Xrm.Utility.getGlobalContext().getClientUrl(); } catch (_) { /* outside a CRM page frame */ }
    const org = location.pathname.split('/').filter(Boolean)[0];
    return location.origin + (org && org.toLowerCase() !== 'main.aspx' ? '/' + org : '');
  })();
  // v9.0 is served by every 9.x server, on-prem 9.1 included (readiness F11).
  const apiBase = clientUrl + '/api/data/v9.0/';
  const get = async (path) => {
    const response = await fetch(apiBase + path, { credentials: 'same-origin', headers: { Accept: 'application/json', 'OData-MaxVersion': '4.0', 'OData-Version': '4.0' } });
    const body = await response.text();
    if (!response.ok) { const error = new Error(response.status + ' ' + body.slice(0, 200)); error.status = response.status; throw error; }
    return JSON.parse(body);
  };
  console.log('Survey Engine ' + RUN.label + ' on ' + clientUrl + ': read-only, please wait…');
  const report = await RUN.execute(get);
  report.org = RUN.org; report.url = clientUrl; report.ranAt = new Date().toISOString(); report.kitDate = KIT_DATE;
  if (report.checks) console.table(report.checks.map((check) => ({ id: check.id, status: check.status, check: check.title, detail: check.detail })));
  const file = 'survey-' + RUN.file + '-' + new Date().toISOString().slice(0, 10) + '.json';
  const link = document.createElement('a');
  link.href = URL.createObjectURL(new Blob([JSON.stringify(report, null, 2)], { type: 'application/json' }));
  link.download = file;
  document.body.appendChild(link); link.click(); link.remove();
  console.log('Downloaded ' + file + '. Send it back to MSS.');
})().catch((error) => console.error('Survey Engine check failed:', error));
`;

function script({ title, kitDate, kit, run }) {
  return [
    `/* Survey Engine on-prem kit ${kitDate}: ${title}.`,
    ' * READ-ONLY (GET requests only). Paste the whole file into the browser console (F12) on a CRM page,',
    ' * signed in as a System Administrator. Generated by onprem/build-browser-checks.mjs; do not edit. */',
    `const KIT_DATE = ${JSON.stringify(kitDate)};`,
    `const KIT = ${JSON.stringify(kit)};`,
    CHECKS,
    run,
    BROWSER_RUNNER,
  ].join('\n');
}

function preflightRun(org, config) {
  return `const CONFIG = ${JSON.stringify(config)};\nconst RUN = { org: '${org}', label: 'preflight (${org})', file: 'preflight-${org}', execute: (get) => SurveyChecks.preflight({ get, kit: KIT, config: CONFIG }) };`;
}

function run() {
  const { values } = parseArgs({ options: { date: { type: 'string' } } });
  const kitDir = resolve(HERE, `../onprem-deploy/${values.date}`);
  const kit = readKitFacts(kitDir);
  const out = resolve(kitDir, 'scripts');
  mkdirSync(out, { recursive: true });
  const write = (name, content) => { writeFileSync(resolve(out, name), content); console.log(`  wrote scripts/${name} (${content.length} chars)`); };
  for (const org of ORGS) {
    const config = JSON.parse(readFileSync(resolve(kitDir, `config/${org}.json`), 'utf8'));
    write(`survey-preflight-${org}.console.js`, script({ title: `preflight for ${org}`, kitDate: values.date, kit, run: preflightRun(org, config) }));
  }
  write('survey-rollback-backup.console.js', script({ title: 'rollback backup of the Form Engine designer, runtime and plugin', kitDate: values.date, kit,
    run: "const RUN = { org: 'this org', label: 'rollback backup', file: 'rollback-backup', execute: (get) => SurveyChecks.rollbackBackup({ get, kit: KIT }) };" }));
  write('survey-post-import.console.js', script({ title: 'post-import verification', kitDate: values.date, kit,
    run: "const RUN = { org: 'this org', label: 'post-import check', file: 'post-import', execute: (get) => SurveyChecks.postImport({ get, kit: KIT }) };" }));
}

run();
