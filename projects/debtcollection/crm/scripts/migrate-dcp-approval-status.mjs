/**
 * migrate-dcp-approval-status.mjs — the approved shared-choice migration (docs/SharedChoiceAssessment.md),
 * cloud sandbox only (org5869857f). Never run against HL CRM or QDB1: they receive the result by import.
 *
 *   --backup     Save every Approval Status value (templates and activities) and the six columns'
 *                definitions to docs/evidence/migrations/. Refuses to overwrite an existing backup.
 *   --check      Gate 4: re-reads metadata dependencies of the six columns, the retirement data, and
 *                whether the new choice name is free. Writes the result next to the backup.
 *   --migrate    Creates qdb_dcp_approval_status (0 Return, 1 Approve); rebinds the two Approval
 *                Status columns under unchanged logical names; retires the four unused columns;
 *                restores and verifies the backed-up values. Stops at the first failed gate.
 *   --rollback   Rebinds the Approval Status columns to QDB's choice and restores the values; recreates
 *                the retired columns empty, from the backed-up definitions.
 *   --execute    Required for --migrate and --rollback to write anything; without it they only report.
 *
 * QDB's own global choices are never created, changed or deleted here.
 */
import { execFileSync } from 'node:child_process';
import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadConfig, acquireToken } from './lib/crm-client.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
const EVIDENCE = resolve(HERE, '../../docs/evidence/migrations');
const BACKUP = resolve(EVIDENCE, '2026-10-04-approval-status-backup.json');
const CHECK = resolve(EVIDENCE, '2026-10-04-dependency-check.json');
const VERIFY = resolve(EVIDENCE, '2026-10-04-approval-status-restore-verification.json');
const SOLUTION = 'qdb_debtcollection';
const AUTHORISED_ORG = 'org5869857f';
const NEW_CHOICE = { name: 'qdb_dcp_approval_status', label: 'DCP Approval Status', options: [[0, 'Return'], [1, 'Approve']] };
const QDB_APPROVAL_CHOICE = 'qdb_approval_status';

/** [table, entity set, column, business id column, name column, fate] */
const COLUMNS = [
  ['qdb_collectionactivity', 'qdb_collectionactivities', 'qdb_approvalstatus', 'qdb_activitynumber', 'subject', 'rebind'],
  ['qdb_communicationtemplate', 'qdb_communicationtemplates', 'qdb_approvalstatus', 'qdb_code', 'qdb_name', 'rebind'],
  ['qdb_collectioncase', 'qdb_collectioncases', 'qdb_risklevel', 'qdb_casenumber', 'qdb_casenumber', 'retire'],
  ['qdb_collectioncase', 'qdb_collectioncases', 'qdb_priority', 'qdb_casenumber', 'qdb_casenumber', 'retire'],
  ['qdb_collectionstrategy', 'qdb_collectionstrategies', 'qdb_risklevel', 'qdb_code', 'qdb_name', 'retire'],
  ['qdb_assignmentconfiguration', 'qdb_assignmentconfigurations', 'qdb_risklevel', 'qdb_name', 'qdb_name', 'retire'],
];
const ALLOWED_DEPENDENTS = new Set([60, 26]);  // system form, view — regenerated by provision-dcp-app-ux.mjs
const isExecute = process.argv.includes('--execute');

const cfg = loadConfig();
if (!cfg.orgUrl.includes(AUTHORISED_ORG)) { console.error(`Refusing: ${cfg.orgUrl} is not ${AUTHORISED_ORG}`); process.exit(1); }
const token = await acquireToken(cfg);
const headers = { Authorization: `Bearer ${token}`, Accept: 'application/json', 'Content-Type': 'application/json', 'OData-MaxVersion': '4.0', 'OData-Version': '4.0', 'MSCRM.SolutionUniqueName': SOLUTION };

async function call(method, path, body) {
  const response = await fetch(cfg.apiBase + path, { method, headers, ...(body !== undefined ? { body: JSON.stringify(body) } : {}) });
  const text = await response.text();
  if (!response.ok) throw new Error(`${method} ${path} → ${response.status}: ${text.slice(0, 400)}`);
  return text ? JSON.parse(text) : {};
}
/** Reads are idempotent, so a dropped connection (common right after a publish) is retried; writes never are. */
async function get(path) {
  for (let attempt = 1; ; attempt += 1) {
    try {
      return await call('GET', path);
    } catch (error) {
      const isNetworkFailure = error instanceof TypeError;
      if (!isNetworkFailure || attempt === 4) throw error;
      console.log(`  (read retry ${attempt} after: ${error.message})`);
      await new Promise(done => setTimeout(done, 5000 * attempt));
    }
  }
}
const tryGet = path => get(path).catch(error => ({ error: error.message }));
const label = text => ({ '@odata.type': 'Microsoft.Dynamics.CRM.Label', LocalizedLabels: [{ '@odata.type': 'Microsoft.Dynamics.CRM.LocalizedLabel', Label: text, LanguageCode: 1033 }] });
const attributePath = (table, column) => `/EntityDefinitions(LogicalName='${table}')/Attributes(LogicalName='${column}')`;
const fail = message => { console.error(`\n[STOP] ${message}`); process.exit(2); };

// ── Backup ──────────────────────────────────────────────────────────────────

async function definitionOf(table, column) {
  const a = await tryGet(`${attributePath(table, column)}/Microsoft.Dynamics.CRM.PicklistAttributeMetadata?$select=LogicalName,SchemaName,MetadataId,RequiredLevel,DisplayName,Description&$expand=GlobalOptionSet($select=Name,MetadataId)`);
  // Only a 404 means "absent". Any other failure (throttling, a publish in progress) must stop the run:
  // treating it as absent once made the migration skip a column it should have deleted.
  if (a.error && /→ 404:/.test(a.error)) return { exists: false };
  if (a.error) throw new Error(`could not read ${table}.${column}: ${a.error}`);
  return { exists: true, schemaName: a.SchemaName, metadataId: a.MetadataId, requiredLevel: a.RequiredLevel?.Value, displayName: a.DisplayName?.UserLocalizedLabel?.Label, description: a.Description?.UserLocalizedLabel?.Label ?? '', choice: a.GlobalOptionSet?.Name };
}

async function valuesOf([table, set, column, idColumn, nameColumn]) {
  const primary = table === 'qdb_collectionactivity' ? 'activityid' : `${table}id`;
  const rows = await get(`/${set}?$select=${[primary, column, idColumn, nameColumn].filter((v, i, all) => all.indexOf(v) === i).join(',')}&$filter=${column} ne null`);
  return rows.value.map(row => ({ table, entitySet: set, id: row[primary], businessId: row[idColumn] ?? null, name: row[nameColumn] ?? null, column, value: row[column] }));
}

async function backup() {
  if (existsSync(BACKUP)) fail(`a backup already exists at ${BACKUP}; it is never overwritten`);
  const definitions = [];
  for (const [table, , column, , , fate] of COLUMNS) definitions.push({ table, column, fate, ...(await definitionOf(table, column)) });
  const records = [];
  for (const entry of COLUMNS) records.push(...(await valuesOf(entry)));
  mkdirSync(EVIDENCE, { recursive: true });
  writeFileSync(BACKUP, JSON.stringify({ takenAt: new Date().toISOString(), organisation: cfg.orgUrl, definitions, records }, null, 2));
  console.log(`[BACKUP] ${records.length} value(s) and ${definitions.length} definition(s) → ${BACKUP}`);
  for (const r of records) console.log(`  ${r.table}.${r.column} ${r.businessId ?? r.id} = ${r.value}`);
}

// ── Gate 4 ──────────────────────────────────────────────────────────────────

/** Plugin steps and their images registered on one table — read once per table, filtered server-side. */
async function pluginRegistrationsOf(table) {
  const filters = (await get(`/sdkmessagefilters?$select=sdkmessagefilterid&$filter=primaryobjecttypecode eq '${table}'`)).value.map(f => f.sdkmessagefilterid);
  const steps = [];
  for (const filterId of filters) steps.push(...(await get(`/sdkmessageprocessingsteps?$select=sdkmessageprocessingstepid,name,filteringattributes&$filter=_sdkmessagefilterid_value eq ${filterId}`)).value);
  const images = [];
  for (const step of steps) images.push(...(await get(`/sdkmessageprocessingstepimages?$select=name,attributes&$filter=_sdkmessageprocessingstepid_value eq ${step.sdkmessageprocessingstepid}`)).value);
  return { steps, images };
}

const mentions = (list, column) => (list ?? '').split(',').map(name => name.trim()).includes(column);

async function formulaColumnsUsing(table, column) {
  const formulas = (await get(`/EntityDefinitions(LogicalName='${table}')/Attributes?$select=LogicalName,SourceType`)).value.filter(a => a.SourceType === 1 || a.SourceType === 2).map(a => a.LogicalName);
  const hits = [];
  for (const name of formulas) {
    const formula = await tryGet(`${attributePath(table, name)}?$select=FormulaDefinition`);
    if ((formula.FormulaDefinition ?? '').includes(column)) hits.push(name);
  }
  return hits;
}

async function dependencyReport(table, column) {
  const definition = await definitionOf(table, column);
  if (!definition.exists) return { table, column, exists: false };
  const deps = (await get(`/RetrieveDependenciesForDelete(ObjectId=${definition.metadataId},ComponentType=2)`)).value ?? [];
  const { steps: allSteps, images: allImages } = await pluginRegistrationsOf(table);
  const steps = allSteps.filter(s => mentions(s.filteringattributes, column)).map(s => s.name);
  const images = allImages.filter(i => mentions(i.attributes, column)).map(i => i.name);
  const processes = (await get(`/workflows?$select=name,category&$filter=primaryentity eq '${table}' and contains(xaml,'${column}')`)).value
    .map(w => `${w.name} (category ${w.category})`);
  const formulaHits = await formulaColumnsUsing(table, column);
  console.log(`  checked ${table}.${column}: ${deps.length} dependent(s), ${allSteps.length} step(s) on the table`);
  return {
    table, column, exists: true,
    dependents: deps.map(d => ({ type: d.dependentcomponenttype, id: d.dependentcomponentobjectid })),
    blocking: deps.filter(d => !ALLOWED_DEPENDENTS.has(d.dependentcomponenttype)).map(d => d.dependentcomponenttype),
    pluginSteps: steps, stepImages: images, processesAndBusinessRules: processes, calculatedOrRollup: formulaHits,
  };
}

async function check() {
  const columns = [];
  for (const [table, set, column, , , fate] of COLUMNS) {
    const report = await dependencyReport(table, column);
    report.fate = fate;
    if (fate === 'retire' && report.exists) report.valuesPresent = (await get(`/${set}?$select=createdon&$top=1&$count=true&$filter=${column} ne null`))['@odata.count'];
    columns.push(report);
  }
  const choice = await tryGet(`/GlobalOptionSetDefinitions(Name='${NEW_CHOICE.name}')`);
  const result = { checkedAt: new Date().toISOString(), newChoiceExists: !choice.error, newChoiceOptions: choice.Options?.map(o => o.Value), columns };
  mkdirSync(EVIDENCE, { recursive: true });
  writeFileSync(CHECK, JSON.stringify(result, null, 2));
  const problems = columns.flatMap(c => [
    ...(c.blocking ?? []).map(t => `${c.table}.${c.column}: dependent component type ${t}`),
    ...(c.pluginSteps ?? []).map(s => `${c.table}.${c.column}: plugin step ${s}`),
    ...(c.stepImages ?? []).map(s => `${c.table}.${c.column}: step image ${s}`),
    ...(c.processesAndBusinessRules ?? []).map(s => `${c.table}.${c.column}: process ${s}`),
    ...(c.calculatedOrRollup ?? []).map(s => `${c.table}.${c.column}: formula column ${s}`),
    ...(c.fate === 'retire' && c.valuesPresent ? [`${c.table}.${c.column}: ${c.valuesPresent} row(s) hold a value`] : []),
  ]);
  if (result.newChoiceExists && JSON.stringify(result.newChoiceOptions) !== '[0,1]') problems.push(`${NEW_CHOICE.name} exists with unexpected options ${result.newChoiceOptions}`);
  for (const c of columns) console.log(`  ${c.table}.${c.column} [${c.fate}] exists=${c.exists} forms/views=${(c.dependents ?? []).length} values=${c.valuesPresent ?? '-'}`);
  return problems;
}

// ── Migrate ─────────────────────────────────────────────────────────────────

function regenerate(exclude) {
  const tables = [...new Set(COLUMNS.map(c => c[0]))].join(',');
  const args = [resolve(HERE, 'provision-dcp-app-ux.mjs'), `--only=${tables}`, ...(exclude ? [`--exclude=${exclude}`] : [])];
  console.log(`  [REGENERATE] forms and views${exclude ? ` without ${exclude}` : ''}`);
  if (isExecute) execFileSync(process.execPath, args, { stdio: 'inherit', env: process.env });
}

const pause = milliseconds => new Promise(done => setTimeout(done, milliseconds));

/** A just-created choice is not readable by name at once (metadata cache); poll for up to a minute. */
async function readChoiceAfterCreate() {
  for (let attempt = 1; attempt <= 12; attempt += 1) {
    const choice = await tryGet(`/GlobalOptionSetDefinitions(Name='${NEW_CHOICE.name}')`);
    if (!choice.error) return choice;
    await pause(5000);
  }
  fail(`${NEW_CHOICE.name} was created but is still not readable after a minute`);
}

function assertChoiceOptions(choice) {
  const actual = JSON.stringify(choice.Options.map(o => [o.Value, o.Label.UserLocalizedLabel.Label]));
  if (actual !== JSON.stringify(NEW_CHOICE.options)) fail(`${NEW_CHOICE.name} has unexpected options ${actual}`);
}

async function ensureChoice() {
  const existing = await tryGet(`/GlobalOptionSetDefinitions(Name='${NEW_CHOICE.name}')`);
  if (!existing.error) { assertChoiceOptions(existing); return existing.MetadataId; }
  console.log(`  [CREATE] global choice ${NEW_CHOICE.name}`);
  if (!isExecute) return undefined;
  await call('POST', '/GlobalOptionSetDefinitions', {
    '@odata.type': 'Microsoft.Dynamics.CRM.OptionSetMetadata', Name: NEW_CHOICE.name, DisplayName: label(NEW_CHOICE.label),
    Description: label('Approval decision on a DCP communication template or collection activity. Owned by DCP.'),
    IsGlobal: true, OptionSetType: 'Picklist',
    Options: NEW_CHOICE.options.map(([value, text]) => ({ Value: value, Label: label(text) })),
  });
  const created = await readChoiceAfterCreate();
  assertChoiceOptions(created);
  return created.MetadataId;
}

async function deleteColumn(table, column) {
  const deps = (await get(`/RetrieveDependenciesForDelete(ObjectId=${(await definitionOf(table, column)).metadataId},ComponentType=2)`)).value ?? [];
  console.log(`  [DELETE] ${table}.${column}${isExecute ? '' : ` (${deps.length} form/view reference(s) today, cleared by regeneration first)`}`);
  if (isExecute && deps.length > 0) fail(`${table}.${column} still has ${deps.length} dependent component(s) after regeneration`);
  if (isExecute) await call('DELETE', attributePath(table, column));
}

/** Metadata reads lag a recreate and can still return the deleted column's definition; wait for the new one. */
async function readColumnAfterCreate(table, column, expectedChoice) {
  for (let attempt = 1; attempt <= 12; attempt += 1) {
    const definition = await definitionOf(table, column);
    if (definition.choice === expectedChoice) return definition;
    await pause(5000);
  }
  fail(`${table}.${column} still does not report choice ${expectedChoice} after a minute`);
}

async function createChoiceColumn(definition, choiceName) {
  console.log(`  [CREATE] ${definition.table}.${definition.column} → ${choiceName}`);
  if (!isExecute) return;
  const choice = await get(`/GlobalOptionSetDefinitions(Name='${choiceName}')?$select=MetadataId`);
  await call('POST', `/EntityDefinitions(LogicalName='${definition.table}')/Attributes`, {
    '@odata.type': 'Microsoft.Dynamics.CRM.PicklistAttributeMetadata', SchemaName: definition.schemaName,
    DisplayName: label(definition.displayName), Description: label(definition.description ?? ''),
    RequiredLevel: { Value: definition.requiredLevel, CanBeChanged: true, ManagedPropertyLogicalName: 'canmodifyrequirementlevelsettings' },
    'GlobalOptionSet@odata.bind': `/GlobalOptionSetDefinitions(${choice.MetadataId})`,
  });
  const created = await readColumnAfterCreate(definition.table, definition.column, choiceName);
  if (created.schemaName !== definition.schemaName || created.choice !== choiceName) fail(`${definition.table}.${definition.column} was not recreated as defined`);
}

async function publishRebindTables() {
  const entities = [...new Set(COLUMNS.filter(c => c[5] === 'rebind').map(c => `<entity>${c[0]}</entity>`))].join('');
  console.log('  [PUBLISH] rebound tables, so the Web API model knows the recreated columns');
  if (isExecute) await call('POST', '/PublishXml', { ParameterXml: `<importexportxml><entities>${entities}</entities></importexportxml>` });
}

/** Setting the same value twice is harmless, so only the "model not refreshed yet" refusal is retried. */
async function restoreValue(record) {
  for (let attempt = 1; ; attempt += 1) {
    try {
      return await call('PATCH', `/${record.entitySet}(${record.id})`, { qdb_approvalstatus: record.value });
    } catch (error) {
      if (!/Invalid property 'qdb_approvalstatus'/.test(error.message) || attempt === 12) throw error;
      await pause(10000);
    }
  }
}

async function restoreAndVerify(saved, choiceName) {
  await publishRebindTables();
  for (const record of saved.records.filter(r => r.column === 'qdb_approvalstatus')) {
    console.log(`  [RESTORE] ${record.table} ${record.businessId ?? record.id} = ${record.value}`);
    if (isExecute) await restoreValue(record);
  }
  if (!isExecute) return;
  const after = [];
  for (const entry of COLUMNS.filter(c => c[5] === 'rebind')) after.push(...(await valuesOf(entry)));
  const before = saved.records.filter(r => r.column === 'qdb_approvalstatus');
  const changed = before.filter(b => after.find(a => a.id === b.id)?.value !== b.value);
  const unexpected = after.filter(a => !before.some(b => b.id === a.id));
  const verification = { verifiedAt: new Date().toISOString(), boundTo: choiceName, beforeCount: before.length, afterCount: after.length, changed, unexpected, after };
  writeFileSync(VERIFY, JSON.stringify(verification, null, 2));
  console.log(`  [VERIFY] before ${before.length} · after ${after.length} · changed ${changed.length} · unexpected ${unexpected.length}`);
  if (before.length !== after.length || changed.length || unexpected.length) fail('restored values differ from the backup — see the verification file');
}

/**
 * Columns still on QDB's choice must hold exactly the backed-up values. Columns already deleted or
 * rebound by an earlier, interrupted run are restored from the backup, so they are not compared.
 */
async function assertUnmigratedDataMatchesBackup(saved) {
  for (const entry of COLUMNS.filter(c => c[5] === 'rebind')) {
    const [table, , column] = entry;
    const current = await definitionOf(table, column);
    if (!current.exists || current.choice !== QDB_APPROVAL_CHOICE) { console.log(`  [RESUME] ${table}.${column} already migrated past its backup point`); continue; }
    const live = (await valuesOf(entry)).map(r => [r.id, r.value]).sort();
    const backedUp = saved.records.filter(r => r.table === table && r.column === column).map(r => [r.id, r.value]).sort();
    if (JSON.stringify(live) !== JSON.stringify(backedUp)) fail(`${table}.${column} data changed since the backup; take a new backup`);
  }
}

async function migrate() {
  if (!existsSync(BACKUP)) fail('no backup; run --backup first');
  const saved = JSON.parse(readFileSync(BACKUP, 'utf8'));
  await assertUnmigratedDataMatchesBackup(saved);
  const problems = await check();
  if (problems.length) fail(`Gate 4 failed:\n  ${problems.join('\n  ')}`);
  await ensureChoice();
  regenerate('qdb_approvalstatus');
  for (const [table, , column, , , fate] of COLUMNS) {
    const current = await definitionOf(table, column);
    if (current.exists && (fate === 'retire' || current.choice !== NEW_CHOICE.name)) await deleteColumn(table, column);
  }
  for (const definition of saved.definitions.filter(d => d.fate === 'rebind')) {
    if ((await definitionOf(definition.table, definition.column)).choice === NEW_CHOICE.name) console.log(`  [KEEP] ${definition.table}.${definition.column} already → ${NEW_CHOICE.name}`);
    else await createChoiceColumn(definition, NEW_CHOICE.name);
  }
  await restoreAndVerify(saved, NEW_CHOICE.name);
  regenerate();
  if (isExecute) await call('POST', '/PublishXml', { ParameterXml: `<importexportxml><entities>${[...new Set(COLUMNS.map(c => `<entity>${c[0]}</entity>`))].join('')}</entities><optionsets><optionset>${NEW_CHOICE.name}</optionset></optionsets></importexportxml>` });
  console.log(isExecute ? '\n[DONE] migration complete' : '\n[DRY RUN] nothing was written');
}

async function rollback() {
  if (!existsSync(BACKUP)) fail('no backup to roll back to');
  const saved = JSON.parse(readFileSync(BACKUP, 'utf8'));
  regenerate('qdb_approvalstatus');
  for (const definition of saved.definitions.filter(d => d.fate === 'rebind')) {
    if ((await definitionOf(definition.table, definition.column)).exists) await deleteColumn(definition.table, definition.column);
    await createChoiceColumn(definition, QDB_APPROVAL_CHOICE);
  }
  for (const definition of saved.definitions.filter(d => d.fate === 'retire' && d.exists)) {
    if (!(await definitionOf(definition.table, definition.column)).exists) await createChoiceColumn(definition, definition.choice);
  }
  await restoreAndVerify(saved, QDB_APPROVAL_CHOICE);
  console.log(isExecute ? '\n[DONE] rollback complete — restore the generator lists from git before regenerating forms' : '\n[DRY RUN] nothing was written');
}

if (process.argv.includes('--backup')) await backup();
else if (process.argv.includes('--check')) { const problems = await check(); console.log(problems.length ? `\n[GATE 4 FAILED]\n  ${problems.join('\n  ')}` : '\n[GATE 4 PASSED]'); }
else if (process.argv.includes('--migrate')) await migrate();
else if (process.argv.includes('--rollback')) await rollback();
else console.log('Choose --backup, --check, --migrate or --rollback (add --execute to write).');
